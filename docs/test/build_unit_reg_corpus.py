# ─── โหลด units ──────────────────────────────────────────────
by_type: dict[str, list[dict]] = defaultdict(list)
by_shop: dict[str, list[dict]] = defaultdict(list)
with UNITS.open(encoding="utf-8") as f:
    for line in f:
        u = json.loads(line)
        if u.get("sellable"):
            by_type[u.get("product_type") or "none"].append(u)
        by_shop[u.get("shop") or "?"].append(u)


def pick(ptype: str, n: int, with_code: bool = False) -> list[dict]:
    pool = by_type.get(ptype, [])
    if with_code:
        pool = [u for u in pool if u.get("model_codes")]
    return rng.sample(pool, min(n, len(pool)))


Q: list[dict] = []


def add(topic: str, message: str, shop: str | None = None) -> None:
    Q.append({"id": f"q{len(Q)+1:03d}", "topic": topic,
              "shop": shop, "message": message})


